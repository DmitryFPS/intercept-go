package application

import "errors"

// ErrSourceLineageLimit означает, что зарегистрированная рабочая точка
// исчерпала защитный предел уникальных источников. Повтор пакета не освободит
// место, поэтому транспорт должен отправить его в карантин и продолжить очередь.
var ErrSourceLineageLimit = errors.New("превышен защитный предел уникальных перехватов рабочей точки")

// ErrSourceRevisionConflict означает, что под одной и той же версией EAVC
// пришло другое содержимое. Выбирать победителя по сетевому порядку опасно:
// конфликт отправляется в карантин и не меняет уже опубликованный перехват.
var ErrSourceRevisionConflict = errors.New("одна версия EAVC содержит разные данные")
